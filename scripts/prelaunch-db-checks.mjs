    let row=(await db.query('select notice_version,notice_acknowledged_at,marketing_email_consent,withdrawn_at from launch_interest where user_id=$1',[first])).rows[0];
    assert.equal(row.notice_version,notice);assert.ok(row.notice_acknowledged_at);assert.equal(row.marketing_email_consent,false);assert.equal(row.withdrawn_at,null);
