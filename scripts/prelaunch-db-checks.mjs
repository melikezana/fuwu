    await rejects("select save_launch_interest_v2(null,null,$1,false,false,'')",[notice],/notice_required/);
    await rejects("select save_launch_interest_v2(null,null,'prelaunch-2026-10-30',true,false,'')",[],/notice_required/);
    await rejects("select save_launch_interest_v2(null,null,$1,true,true,$2)",[notice,eti],/marketing_closed/);
