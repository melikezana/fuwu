    await db.query("insert into auth.users(id,email,email_confirmed_at) values($1,'TEST-v2-first@example.invalid',now()),($2,'TEST-v2-second@example.invalid',now())",[first,second]);
    await db.query("insert into auth.users(id,email,phone,phone_confirmed_at) values($1,'TEST-v2-applicant@example.invalid','905550000099',now())",[applicant]);
