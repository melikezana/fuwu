    checks.push('Prelaunch: compare-and-clear announcement is admin-only, audited and leaves maintenance unchanged');
    // 13 Kasım 2026 · Aydınlatma beyanı ve ticari e-posta onayı ayrı, sürümlü (KVKK İlke Kararı 2026/347; 6563 s. Kanun).
    const notice='aydinlatma-acilis-2026-11-13', eti='eti-eposta-2026-11-13';
    const first='ab000000-0000-4000-8000-000000000011', second='ab000000-0000-4000-8000-000000000012', applicant='ab000000-0000-4000-8000-000000000013';
